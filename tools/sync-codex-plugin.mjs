// Builds plugins/ai-edit-studio (the OpenAI Codex plugin) from the shared sources: skills/, the version and
// an MCP bootstrap. Codex copies only the plugin folder into its cache, so the folder is self-contained and
// finds the engine through the per-user settings file (src/settings.mjs) that the installer and
// `node cli.mjs codex-setup --plugin` write (or AI_EDIT_STUDIO_HOME).
// Run after changing skills/ or the version: node tools/sync-codex-plugin.mjs   (--check: fail if stale)
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { STUDIO_VERSION } from '../src/agent-tools.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'plugins', 'ai-edit-studio');

export const BOOTSTRAP = [
  "const fs=require('fs'),os=require('os'),path=require('path'),{pathToFileURL}=require('url');",
  "const f=process.platform==='win32'?path.join(process.env.APPDATA||path.join(os.homedir(),'AppData','Roaming'),'AI Edit Studio','settings.json'):path.join(process.env.XDG_CONFIG_HOME||path.join(os.homedir(),'.config'),'ai-edit-studio','settings.json');",
  "let c={};try{c=JSON.parse(fs.readFileSync(f,'utf8'))}catch{}",
  "const engine=process.env.AI_EDIT_STUDIO_HOME||c.engine;",
  "const launcher=engine&&path.join(engine,'plugin','mcp-launch.mjs');",
  "if(!launcher||!fs.existsSync(launcher)){console.error('AI Edit Studio engine not found. Run the AI Edit Studio installer (or: node cli.mjs codex-setup --plugin in the engine folder), or set AI_EDIT_STUDIO_HOME.');process.exit(1)}",
  'import(pathToFileURL(launcher).href).then(m=>m.main());',
].join('');

export async function expectedFiles() {
  const files = new Map();
  files.set('.codex-plugin/plugin.json', `${JSON.stringify({
    name: 'ai-edit-studio',
    version: STUDIO_VERSION,
    description: 'Local-first video editor for Codex: 59 editing tools (auto-edit, edit by text, captions, reframe, music, render QC, publish packs) plus workflow skills for shorts, clips from long videos, talking heads and game trailers. Footage never leaves the computer.',
    author: { name: 'AI Edit Studio' },
    license: 'MIT',
    keywords: ['video', 'editing', 'shorts', 'tiktok', 'reels', 'captions', 'podcast', 'trailer', 'ffmpeg', 'mcp'],
    skills: './skills/',
    mcpServers: './.mcp.json',
    interface: {
      displayName: 'AI Edit Studio',
      shortDescription: 'Edit video locally: shorts, clips, captions, music, QC.',
      longDescription: 'A local video editor Codex can drive: raw footage or a long video in, checked platform-ready renders out (TikTok, Reels, Shorts, YouTube, Steam). Every change is an undoable revision, every render is measured (loudness, peaks, black frames). Nothing is uploaded or posted.',
      developerName: 'AI Edit Studio',
      category: 'Productivity',
      capabilities: ['Interactive', 'Read', 'Write'],
      brandColor: '#FFB400',
      defaultPrompt: [
        'Use the viral-short skill to make a TikTok from my clips with three hook variants.',
        'Use the long-to-shorts skill to cut my podcast episode into five vertical clips.',
        'Use the quality-gate skill to check my last render before I post it.',
      ],
    },
  }, null, 2)}\n`);
  files.set('.mcp.json', `${JSON.stringify({ mcpServers: { 'ai-edit-studio': { command: 'node', args: ['-e', BOOTSTRAP], startup_timeout_sec: 30, tool_timeout_sec: 300 } } }, null, 2)}\n`);
  for (const dir of (await fs.readdir(path.join(ROOT, 'skills'))).sort()) {
    files.set(`skills/${dir}/SKILL.md`, await fs.readFile(path.join(ROOT, 'skills', dir, 'SKILL.md'), 'utf8'));
  }
  files.set('README.md', `# AI Edit Studio — Codex plugin

Generated by \`node tools/sync-codex-plugin.mjs\` from the engine's \`skills/\`; do not edit here.

1. Run the AI Edit Studio installer (or, in the engine folder, \`node cli.mjs codex-setup --plugin\`).
   It records where the engine is so the plugin can find it.
2. \`codex plugin marketplace add <engine folder>\`, restart Codex, install **AI Edit Studio** from the plugin directory.

Without the plugin system: \`node cli.mjs codex-setup\` registers the MCP server and installs the skills directly.
`);
  return files;
}

async function main() {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [rel, content] of await expectedFiles()) {
    const file = path.join(OUT, rel);
    const current = await fs.readFile(file, 'utf8').catch(() => null);
    if (current?.replace(/\r\n/g, '\n') === content) continue;
    stale.push(rel);
    if (!check) { await fs.mkdir(path.dirname(file), { recursive: true }); await fs.writeFile(file, content); }
  }
  console.log(check ? (stale.length ? `Stale: ${stale.join(', ')}` : 'Codex plugin is up to date.') : `Wrote ${stale.length} file(s) to ${OUT}`);
  if (check && stale.length) process.exitCode = 1;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
